    svg(name, opts) {
      const key = resolveKey(name);
      if (!key) return '';

      const content = ICON_PATHS[key];
      const options = opts || {};

      const width = options.size || options.width || 24;
      const height = options.size || options.height || 24;
      const strokeWidth = options.strokeWidth || 2;
      const fill = options.fill || 'none';
      const userClass = options.className || options.class || '';
      const classes = ('ds-icon ' + userClass).trim();

      // Mặc định aria-hidden="true"; nếu có ariaLabel thì set aria-label và role="img"
      let ariaAttrs = 'aria-hidden="true"';
      if (options.ariaLabel) {
        ariaAttrs = `aria-label="${options.ariaLabel}" role="img"`;
      } else if (options.ariaHidden !== undefined) {
        ariaAttrs = `aria-hidden="${options.ariaHidden}"`;
      }

      return `<svg class="${classes}" ${ariaAttrs} viewBox="0 0 24 24" width="${width}" height="${height}" fill="${fill}" stroke="currentColor" stroke-width="${strokeWidth}" stroke-linecap="round" stroke-linejoin="round">${content}</svg>`;
    }
