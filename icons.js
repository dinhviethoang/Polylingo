  /**
   * Tra cứu tên icon hợp lệ, hỗ trợ tìm trực tiếp, alias, và chuyển đổi tự động
   * giữa camelCase và kebab-case.
   */
  function resolveKey(name) {
    if (!name || typeof name !== 'string') return null;
    if (Object.prototype.hasOwnProperty.call(ICON_PATHS, name)) return name;
    if (Object.prototype.hasOwnProperty.call(ALIASES, name)) return ALIASES[name];

    // Chuyển camelCase sang kebab-case (vd arrowLeft -> arrow-left)
    const kebab = name.replace(/([a-z0-9])([A-Z])/g, '$1-$2').toLowerCase();
    if (Object.prototype.hasOwnProperty.call(ICON_PATHS, kebab)) return kebab;
    if (Object.prototype.hasOwnProperty.call(ALIASES, kebab)) return ALIASES[kebab];

    // Chuyển kebab-case sang camelCase (vd check-circle -> checkCircle)
    const camel = name.replace(/-([a-z0-9])/g, (_, c) => c.toUpperCase());
    if (Object.prototype.hasOwnProperty.call(ALIASES, camel)) return ALIASES[camel];
    if (Object.prototype.hasOwnProperty.call(ICON_PATHS, camel)) return camel;

    return null;
  }

